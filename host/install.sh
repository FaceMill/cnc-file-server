#!/bin/bash
# One-time host bootstrap for Raspberry Pi OS Lite 64-bit (Bookworm). Also written to work
# on Debian 12 / Ubuntu on an x86-64 PC with two network ports (not yet tested there).
# Copy the project to /opt/cnc-server, create .env from .env.example, then:
#   cd /opt/cnc-server && sudo ./host/install.sh
set -euo pipefail

PROJECT_DIR=$(cd "$(dirname "$0")/.." && pwd)
cd "$PROJECT_DIR"
[ -f .env ] || { echo "Create .env from .env.example first." >&2; exit 1; }
set -a; . ./.env; set +a

# FOCAS bridge platform. FANUC's library comes for 32-bit ARM, 32-bit x86 and x86-64 Linux,
# but not 64-bit ARM, so a Pi runs the bridge as a 32-bit ARM container.
if [ -z "${FOCAS_PLATFORM:-}" ]; then
    case "$(uname -m)" in
        aarch64|armv7l|armv8l) FOCAS_PLATFORM=linux/arm/v7 ;;
        x86_64) FOCAS_PLATFORM=linux/amd64 ;;
        i?86) FOCAS_PLATFORM=linux/386 ;;
        *) echo "No FANUC FOCAS library exists for this CPU ($(uname -m))." >&2; exit 1 ;;
    esac
    printf '\n# Set by host/install.sh for this CPU (%s)\nFOCAS_PLATFORM=%s\n' "$(uname -m)" "$FOCAS_PLATFORM" >> .env
    export FOCAS_PLATFORM
fi
echo "FOCAS bridge platform: $FOCAS_PLATFORM"

apt-get update
apt-get -y full-upgrade
apt-get install -y nftables cockpit unattended-upgrades restic curl smartmontools
# brltty claims CH340 USB serial adapters, and ModemManager sends "AT" probes down new
# serial ports (garbage at the CNC). Neither is wanted on a DNC server.
apt-get purge -y brltty modemmanager 2>/dev/null || true
dpkg-reconfigure -f noninteractive unattended-upgrades

# Docker Engine + compose plugin
if ! command -v docker >/dev/null; then
    curl -fsSL https://get.docker.com | sh
fi
# nftables (generated by cnc-admin) is the only firewall; containers use host networking.
mkdir -p /etc/docker
cat > /etc/docker/daemon.json <<'EOF'
{
  "iptables": false,
  "ip6tables": false,
  "log-driver": "json-file",
  "log-opts": { "max-size": "10m", "max-file": "5" }
}
EOF
systemctl restart docker

# Shared file owner and storage root
getent group cncfiles >/dev/null || groupadd -g "$CNC_GID" cncfiles
getent passwd cncfiles >/dev/null || useradd -M -u "$CNC_UID" -g cncfiles -s /usr/sbin/nologin cncfiles
mkdir -p /srv/cnc
chown cncfiles:cncfiles /srv/cnc
chmod 0770 /srv/cnc

mkdir -p config generated data/caddy data/portainer
chmod 0700 config generated

# Network connections (office-net / cnc-net)
./host/setup-network.sh

# Site config, generated files, admin password
docker compose build --pull
# The FOCAS library must load on this host (a 32-bit ARM container needs a kernel with
# 32-bit support: a Pi has it, some other ARM servers don't). Only FOCAS depends on it.
if docker run --rm --platform "$FOCAS_PLATFORM" local/cnc-focas:1.0 python -c "import focas; focas.lib()"; then
    echo "FOCAS library loads ($FOCAS_PLATFORM)."
else
    echo "WARNING: the FOCAS library doesn't load on this host ($FOCAS_PLATFORM). FANUC FOCAS machines" >&2
    echo "         won't work; everything else will. See focas/lib/README.md." >&2
fi
if [ ! -f config/site.json ]; then
    docker compose run --rm --no-deps cnc-admin python -m cncadmin.cli init
fi
docker compose run --rm --no-deps cnc-admin python -m cncadmin.cli render
docker compose run --rm --no-deps cnc-admin python -m cncadmin.cli set-admin-password

# Firewall: boot-time include of the generated rules. If they are ever missing or
# invalid, a locked-down fallback is loaded instead of booting with no firewall.
sed "s|@PROJECT_DIR@|$PROJECT_DIR|" host/nftables.conf > /etc/nftables.conf
install -m 0644 host/nftables-fallback.conf /etc/nftables-fallback.conf
install -D -m 0644 host/nftables-fallback.service.conf /etc/systemd/system/nftables.service.d/fallback.conf
nft -c -f /etc/nftables.conf
nft -c -f /etc/nftables-fallback.conf
systemctl daemon-reload
systemctl enable nftables
nft -f /etc/nftables.conf

docker compose up -d

# Backups (nightly; reports "not configured" until host/setup-backup.sh is run) and
# the host health snapshot (every 5 minutes) shown on the admin page.
for unit in cnc-backup.service cnc-backup.timer cnc-health.service cnc-health.timer; do
    sed "s|@PROJECT_DIR@|$PROJECT_DIR|g" "host/systemd/$unit" > "/etc/systemd/system/$unit"
done
systemctl daemon-reload
systemctl enable --now cnc-health.timer cnc-backup.timer
python3 host/health.py || true
host/backup.sh || true

echo
echo "Done. Admin page: https://$OFFICE_HOSTNAME:8443  (user: admin)"
echo "      Cockpit:    https://$OFFICE_HOSTNAME:9090  (Pi login)"
echo "      Portainer is off; see docker-compose.yml to enable it behind an SSH tunnel."
echo
echo "Next: set up backups with  sudo $PROJECT_DIR/host/setup-backup.sh"
